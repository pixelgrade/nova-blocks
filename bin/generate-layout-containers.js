/**
 * Prebuild step (Task 5.1): emit the SCSS half of the single layout-container
 * list from `packages/utils/src/layout-containers.js`.
 *
 * The JS module is the source of truth; this writes
 * `packages/base-styles/_layout-containers.generated.scss` defining
 * `$nb-layout-grid-parents` and `$nb-layout-passthrough-containers` (the
 * comma-joined selector strings) so the SCSS
 * (`_content-layout.scss` imports it; `_layout.scss` interpolates it) and the
 * JS (`break-align.js`) can never drift. Runs before the SCSS compile in
 * `build:packages`. The generated file is committed so a plain SCSS compile
 * works without a prebuild, and `layout-containers.test.js` asserts the two
 * halves stay identical.
 */

const fs = require( 'fs' );
const path = require( 'path' );

const REPO_ROOT = path.resolve( __dirname, '..' );
const SOURCE = path.join( REPO_ROOT, 'packages/utils/src/layout-containers.js' );
const OUT = path.join( REPO_ROOT, 'packages/base-styles/_layout-containers.generated.scss' );

/**
 * Extract the string members of a `<NAME> = [ … ]` array from the source
 * module. Members are single-quoted selector literals (one contains a nested
 * double-quoted attribute selector, which single-quote extraction handles).
 * Kept as text parsing so no ESM/CJS interop is needed at build time.
 *
 * @param {string} source The layout-containers.js file contents.
 * @param {string} name   The exported array name to extract.
 * @return {string[]} The selectors, in source order.
 */
function extractContainers( source, name ) {
	// Anchor on the array's closing `];` — a member selector can itself contain
	// a `]` (the woocommerce attribute selector), so stopping at the first `]`
	// would truncate the list.
	const match = source.match( new RegExp( name + '\\s*=\\s*\\[([\\s\\S]*?)\\];' ) );
	if ( ! match ) {
		throw new Error( 'Could not find ' + name + ' array in ' + SOURCE );
	}
	const members = match[ 1 ].match( /'([^']*)'/g );
	if ( ! members || ! members.length ) {
		throw new Error( name + ' is empty in ' + SOURCE );
	}
	return members.map( ( m ) => m.slice( 1, -1 ) );
}

function main() {
	const source = fs.readFileSync( SOURCE, 'utf8' );
	const containers = extractContainers( source, 'LAYOUT_GRID_CONTAINERS' );
	const selector = containers.join( ', ' );
	const passThroughs = extractContainers( source, 'LAYOUT_PASSTHROUGH_CONTAINERS' );
	const passThroughSelector = passThroughs.join( ', ' );

	const contents =
		'// AUTO-GENERATED by bin/generate-layout-containers.js — DO NOT EDIT.\n' +
		'// Source of truth: packages/utils/src/layout-containers.js (Task 5.1).\n' +
		'// The JS lists and these SCSS lists are pinned equal by\n' +
		'// packages/utils/src/layout-containers.test.js.\n' +
		'$nb-layout-grid-parents: \'' + selector + '\';\n' +
		'$nb-layout-passthrough-containers: \'' + passThroughSelector + '\';\n';

	// Only write when changed, so a clean tree stays clean across rebuilds.
	let existing = '';
	try {
		existing = fs.readFileSync( OUT, 'utf8' );
	} catch ( e ) {
		// no existing file
	}
	if ( existing !== contents ) {
		fs.writeFileSync( OUT, contents );
		console.log( 'generate-layout-containers: wrote ' + path.relative( REPO_ROOT, OUT ) + ' (' + containers.length + ' selectors, ' + passThroughs.length + ' pass-throughs)' );
	} else {
		console.log( 'generate-layout-containers: ' + path.relative( REPO_ROOT, OUT ) + ' already up to date (' + containers.length + ' selectors, ' + passThroughs.length + ' pass-throughs)' );
	}
}

main();
